-- Esquema de AstroCode en Postgres (fase 8).
--
-- Es el estado final del antiguo volcado de MySQL («BD Astrocode.sql») más sus migraciones de estructura
-- (001-004 y 006-010). Lo aplica la migración `001_esquema` sobre una base de datos vacía; los datos
-- de los ejercicios están en `datos-base.sql` y el resto de semillas en migrations.ts.
--
-- Diferencias con MySQL:
--   - Los ids son IDENTITY (las secuencias se ajustan tras cargar los datos base).
--   - TINYINT(1) pasa a BOOLEAN y JSON a JSONB.
--   - tiempo_completado es INTERVAL: TIME de Postgres no pasa de 24 h y el de MySQL sí.
--   - MySQL comparaba el usuario y el correo sin distinguir mayúsculas; aquí se guarda igual,
--     pero los índices únicos y las búsquedas van con lower().

CREATE TABLE categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL UNIQUE,
  descripcion TEXT NULL
);

CREATE TABLE niveles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL UNIQUE,
  puntos INT NOT NULL,
  descripcion TEXT NULL
);

CREATE TABLE tiempos_finalizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  umbral TIME NOT NULL,
  puntos_bonus INT NOT NULL
);

CREATE TABLE insignias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL UNIQUE,
  descripcion TEXT NULL,
  url_imagen VARCHAR(512) NULL
);

CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_usuario VARCHAR(255) NOT NULL,
  correo_electronico VARCHAR(255) NOT NULL,
  contrasena_hash TEXT NOT NULL,
  nombre_completo VARCHAR(255) NULL,
  puntos INT DEFAULT 0,
  creado_el TIMESTAMPTZ NULL DEFAULT now(),
  rol VARCHAR(20) NOT NULL DEFAULT 'alumno'
);
CREATE UNIQUE INDEX usuarios_nombre_usuario ON usuarios (lower(nombre_usuario));
CREATE UNIQUE INDEX usuarios_correo_electronico ON usuarios (lower(correo_electronico));

CREATE TABLE tareas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id BIGINT NOT NULL REFERENCES categorias (id),
  nivel_id BIGINT NOT NULL REFERENCES niveles (id),
  descripcion TEXT NOT NULL,
  fecha_vencimiento DATE NULL,
  prioridad INT NULL CHECK (prioridad BETWEEN 1 AND 5),
  completado BOOLEAN DEFAULT false,
  tiempo_finalizacion_id BIGINT NULL REFERENCES tiempos_finalizacion (id),
  puntos_base INT NULL,
  puntos_bonus INT DEFAULT 0,
  codigo_base TEXT NULL,
  resultado_esperado TEXT NULL,
  titulo VARCHAR(255) NOT NULL DEFAULT '',
  solucion TEXT NULL,
  tipo VARCHAR(20) NOT NULL DEFAULT 'codigo',
  config JSONB NULL
);
CREATE INDEX tareas_categoria_id ON tareas (categoria_id);
CREATE INDEX tareas_nivel_id ON tareas (nivel_id);
CREATE INDEX tareas_tiempo_finalizacion_id ON tareas (tiempo_finalizacion_id);
COMMENT ON COLUMN tareas.codigo_base IS 'Código base/plantilla para el ejercicio';
COMMENT ON COLUMN tareas.resultado_esperado IS 'Resultado esperado que debe mostrar el código al ejecutarse';
COMMENT ON COLUMN tareas.titulo IS 'Título descriptivo del ejercicio';

CREATE TABLE tareas_usuarios (
  usuario_id BIGINT NOT NULL REFERENCES usuarios (id),
  tarea_id BIGINT NOT NULL REFERENCES tareas (id),
  completado_el TIMESTAMPTZ NULL DEFAULT now(),
  tiempo_completado INTERVAL NULL,
  puntos_base INT NULL,
  puntos_bonus INT NULL,
  puntos_totales INT NULL,
  PRIMARY KEY (usuario_id, tarea_id)
);
CREATE INDEX tareas_usuarios_tarea_id ON tareas_usuarios (tarea_id);

CREATE TABLE insignias_usuarios (
  usuario_id BIGINT NOT NULL REFERENCES usuarios (id),
  insignia_id BIGINT NOT NULL REFERENCES insignias (id),
  ganado_el TIMESTAMPTZ NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, insignia_id)
);
CREATE INDEX insignias_usuarios_insignia_id ON insignias_usuarios (insignia_id);

-- Tests que se ejecutan contra el código del alumno. Los ocultos no se le enseñan.
CREATE TABLE tests_tarea (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarea_id BIGINT NOT NULL REFERENCES tareas (id) ON DELETE CASCADE,
  descripcion VARCHAR(255) NOT NULL DEFAULT '',
  codigo_test TEXT NULL,
  entrada TEXT NULL,
  salida_esperada TEXT NOT NULL,
  oculto BOOLEAN NOT NULL DEFAULT false,
  orden INT NOT NULL DEFAULT 0
);
CREATE INDEX tests_tarea_tarea_id ON tests_tarea (tarea_id);
COMMENT ON COLUMN tests_tarea.codigo_test IS 'Código que se añade tras el del alumno (llamadas + print)';
COMMENT ON COLUMN tests_tarea.entrada IS 'stdin para el programa';

-- Registro de pistas pedidas a la IA (para limitar cuántas pide cada alumno)
CREATE TABLE pistas_ia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tarea_id BIGINT NOT NULL REFERENCES tareas (id) ON DELETE CASCADE,
  creado_el TIMESTAMPTZ NULL DEFAULT now()
);
CREATE INDEX pistas_ia_usuario_fecha ON pistas_ia (usuario_id, creado_el);
CREATE INDEX pistas_ia_tarea_id ON pistas_ia (tarea_id);

-- Cada envío de solución (para el puente de mando y la repetición de intentos)
CREATE TABLE intentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tarea_id BIGINT NOT NULL REFERENCES tareas (id) ON DELETE CASCADE,
  codigo TEXT NOT NULL,
  correcto BOOLEAN NOT NULL,
  tests_superados INT NULL,
  tests_totales INT NULL,
  tipo_error VARCHAR(50) NULL,
  segundos_en_tarea INT NULL,
  creado_el TIMESTAMPTZ NULL DEFAULT now()
);
CREATE INDEX intentos_tarea_fecha ON intentos (tarea_id, creado_el);
CREATE INDEX intentos_usuario_fecha ON intentos (usuario_id, creado_el);

-- Fase 1: sabotajes generados (y verificados) a partir de la solución de una tarea
CREATE TABLE sabotajes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarea_original_id BIGINT NOT NULL REFERENCES tareas (id) ON DELETE CASCADE,
  tarea_id BIGINT NULL REFERENCES tareas (id) ON DELETE SET NULL,
  codigo TEXT NOT NULL,
  hash CHAR(64) NOT NULL,
  operador VARCHAR(30) NOT NULL,
  descripcion VARCHAR(255) NOT NULL,
  linea INT NULL,
  lineas_cambiadas INT NOT NULL,
  diff TEXT NOT NULL,
  contexto TEXT NULL,
  dificultad VARCHAR(10) NOT NULL,
  tests_fallidos INT NOT NULL,
  tests_totales INT NOT NULL,
  origen VARCHAR(10) NOT NULL DEFAULT 'ast',
  creado_el TIMESTAMPTZ NULL DEFAULT now(),
  CONSTRAINT sabotajes_original_hash UNIQUE (tarea_original_id, hash)
);
CREATE INDEX sabotajes_tarea_id ON sabotajes (tarea_id);
COMMENT ON COLUMN sabotajes.tarea_id IS 'Tarea tipo sabotaje creada al publicarlo';

-- En Supabase, las tablas de «public» se pueden leer con la API REST y la clave pública del proyecto.
-- AstroCode no la usa (todo pasa por su API GraphQL): con RLS activado y sin políticas, esa vía queda
-- cerrada. La API se conecta como propietaria de las tablas, así que a ella no le afecta.
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE niveles ENABLE ROW LEVEL SECURITY;
ALTER TABLE tiempos_finalizacion ENABLE ROW LEVEL SECURITY;
ALTER TABLE insignias ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE tareas ENABLE ROW LEVEL SECURITY;
ALTER TABLE tareas_usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE insignias_usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE tests_tarea ENABLE ROW LEVEL SECURITY;
ALTER TABLE pistas_ia ENABLE ROW LEVEL SECURITY;
ALTER TABLE intentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE sabotajes ENABLE ROW LEVEL SECURITY;
